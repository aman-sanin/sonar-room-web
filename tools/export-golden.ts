// Golden fixtures for the native port.
//
// Usage:  bun tools/export-golden.ts [outputPath]
//
// The maze is the only part of the simulation that must be bit-identical
// between the web build and the Kotlin port: a seed has to produce the same
// walls, door, keys, and spawns on both sides. This script serialises the
// generator output in a stable, line-oriented format that the JVM tests read
// without needing a JSON dependency.
//
// Format (one block per map, blank line between blocks):
//
//   MAP <seed> <hunt|solo>
//   size <cols> <rows> <cell> <w> <h>
//   start <x> <y>
//   monster <x> <y>
//   solid <cols*rows chars, row-major, '0' open / '1' solid>
//   open <comma-separated flat indices>
//   edges <x1>,<y1>,<x2>,<y2>;...
//   keys <x>,<y>,<color>;...
//   doors <midX>,<midY>,<vertical>,<color>;...
//
// All coordinates are integers because MAP_CELL is even, which keeps the
// fixture free of floating-point formatting differences.

import { mkdirSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { generateMap, mulberry32, type GameMap } from '../src/lib/game/maze'

const HERE = dirname(fileURLToPath(import.meta.url))

/** Seeds chosen to cover both variants, including small and large values. */
const SEEDS = [1, 2, 3, 7, 42, 99, 1234, 8675309]

const outPath = resolve(HERE, process.argv[2] ?? '../../sonar-room/app/src/test/resources/maze-golden.txt')

function solidString(map: GameMap): string {
  let out = ''
  for (let i = 0; i < map.solid.length; i++) out += map.solid[i] === 1 ? '1' : '0'
  return out
}

function encodeMap(seed: number, hunt: boolean): string {
  const map = generateMap(seed, hunt)
  const lines: string[] = []
  lines.push(`MAP ${seed} ${hunt ? 'hunt' : 'solo'}`)
  lines.push(`size ${map.cols} ${map.rows} ${map.cell} ${map.w} ${map.h}`)
  lines.push(`start ${map.start.x} ${map.start.y}`)
  lines.push(`monster ${map.monsterStart.x} ${map.monsterStart.y}`)
  lines.push(`solid ${solidString(map)}`)
  lines.push(`open ${map.open.join(',')}`)
  lines.push(
    `edges ${map.edges.map((e) => `${e.x1},${e.y1},${e.x2},${e.y2}`).join(';')}`,
  )
  lines.push(`keys ${map.keys.map((k) => `${k.x},${k.y},${k.color}`).join(';')}`)
  lines.push(
    `doors ${map.doors.map((d) => `${d.midX},${d.midY},${d.vertical ? 1 : 0},${d.color}`).join(';')}`,
  )
  return lines.join('\n')
}

const blocks: string[] = []
for (const seed of SEEDS) {
  blocks.push(encodeMap(seed, false))
  blocks.push(encodeMap(seed, true))
}

// PRNG goldens: a tiny fixed vector plus the first values after the maze
// shuffle would be consumed, so Kotlin can validate the generator on its own.
const rngLines: string[] = ['RNG mulberry32']
for (const seed of SEEDS) {
  const rng = mulberry32(seed)
  const values: string[] = []
  for (let i = 0; i < 8; i++) values.push(rng().toString())
  rngLines.push(`rng ${seed} ${values.join(',')}`)
}

const footer = [
  'END',
  'Generated by sonar-web/tools/export-golden.ts. Do not edit by hand.',
].join('\n')

mkdirSync(dirname(outPath), { recursive: true })
writeFileSync(outPath, `${rngLines.join('\n')}\n\n${blocks.join('\n\n')}\n\n${footer}\n`)
console.log(`wrote ${outPath}`)
console.log(`${SEEDS.length * 2} maps, ${SEEDS.length} rng vectors`)
